const STYLES: Record<string, MessageKey> = {
  tee: "tee",
  shirt: "shirt",
  hoodie: "hoodie",
  jacket: "jacket",
  pants: "pants",
  shorts: "shorts",
  accessory: "accessory",
};

export function styleText(style: string, lang: Lang): string {
  const key = STYLES[style];
  return key ? t(lang, key) : t(lang, "apparel");
}

export function localizedName(product: { name: string; nameEn?: string }, lang: Lang): string {
  if (lang === "en") return product.nameEn?.trim() || product.name;
  return product.name;
}

export function localizedDescription(product: { description: string; descriptionEn?: string }, lang: Lang): string {
  if (lang === "en") return product.descriptionEn?.trim() || product.description;
  return product.description;
}

